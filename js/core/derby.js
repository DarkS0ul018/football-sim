const derbyIndex = new Map();
DERBIES.forEach(([a, b, title]) => { derbyIndex.set(`${a}|${b}`, title); derbyIndex.set(`${b}|${a}`, title); });

function derbyTitle(a, b) {
    if (!a || !b) return null;
    return derbyIndex.get(`${a.name || a}|${b.name || b}`) || null;
}

// ----- Личные встречи (только дерби), хранятся между турнирами -----
const H2H_KEY = 'footballSimPro.h2h';
function readH2H() {
    try { return JSON.parse(localStorage.getItem(H2H_KEY)) || {}; } catch (e) { return {}; }
}

function h2hKey(a, b) { return [a, b].sort().join('|'); }

function recordH2H(m, winner) {
    if (!m || !derbyTitle(m.team1, m.team2)) return;
    const all = readH2H();
    const key = h2hKey(m.team1.name, m.team2.name);
    const rec = all[key] || { w: {}, d: 0, games: [] };
    const agg = m.aggregateScore || { t1: m.score1, t2: m.score2 };
    if (winner) rec.w[winner.name] = (rec.w[winner.name] || 0) + 1; else rec.d++;
    rec.games.unshift({ t1: m.team1.name, t2: m.team2.name, s: `${agg.t1}:${agg.t2}`, date: new Date().toLocaleDateString('ru-RU') });
    rec.games = rec.games.slice(0, 10);
    all[key] = rec;
    try { localStorage.setItem(H2H_KEY, JSON.stringify(all)); } catch (e) { /* ignore */ }
}

function h2hSummary(a, b) {
    const rec = readH2H()[h2hKey(a.name, b.name)];
    if (!rec) return null;
    return { wa: rec.w[a.name] || 0, wb: rec.w[b.name] || 0, d: rec.d, games: rec.games };
}
