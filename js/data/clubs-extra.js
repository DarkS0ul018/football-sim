(function registerExtraClubs() {
    if (typeof worldTeams === 'undefined') return;
    // Вставляем перед клубами других континентов (они в конце списка)
    const firstNonEu = worldTeams.names.findIndex(n => typeof NON_EUROPEAN_CLUBS !== 'undefined' && NON_EUROPEAN_CLUBS.has(n));
    const at = firstNonEu === -1 ? worldTeams.names.length : firstNonEu;
    EXTRA_CLUBS.forEach((c, i) => {
        if (worldTeams.names.includes(c.name)) return;
        worldTeams.names.splice(at + i, 0, c.name);
        worldTeams.emojis.splice(at + i, 0, c.emoji);
        teamRatings[c.name] = c.rating;
        teamMeta[c.name] = [c.code, c.year];
        if (typeof SQUADS !== 'undefined') SQUADS.world[c.name] = c.squad;
    });
    if (typeof mixedTeams !== 'undefined') {
        mixedTeams.names = [...russianTeams.names, ...worldTeams.names];
        mixedTeams.emojis = [...russianTeams.emojis, ...worldTeams.emojis];
    }
})();
