function filterTeams(data, keep) {
    const out = { names: [], emojis: [] };
    data.names.forEach((n, i) => { if (keep(n)) { out.names.push(n); out.emojis.push(data.emojis[i]); } });
    return out;
}

// Наборы команд для турниров:
// world — европейские клубы, clubwc — все клубы мира (Европа + другие континенты),
// russia — РПЛ, fnl — Первая лига, mixed — РПЛ + Европа, сборные — по турниру
function getTeamsData(teamType) {
    // Сборные: состав турнира из js/data/nations.js
    if (typeof NATION_CUPS !== 'undefined' && NATION_CUPS[teamType]) return { names: NATION_CUPS[teamType].names, emojis: NATION_CUPS[teamType].names.map(() => '') };
    const euro = filterTeams(worldTeams, n => !NON_EUROPEAN_CLUBS.has(n));
    const rpl = filterTeams(russianTeams, n => !FNL_CLUBS.has(n));
    if (teamType === 'mixed') return { names: [...rpl.names, ...euro.names], emojis: [...rpl.emojis, ...euro.emojis] };
    if (teamType === 'clubwc') return worldTeams;
    if (teamType === 'fnl') return filterTeams(russianTeams, n => FNL_CLUBS.has(n));
    if (teamType === 'rusall') return russianTeams;  // РПЛ + Первая лига (Кубок России)
    return teamType === 'russia' ? rpl : euro;
}

// Реальный тип конкретной команды (для смешанного режима)
function getTeamOrigin(teamName) {
    if (typeof NATIONS !== 'undefined' && NATIONS[teamName]) return 'national';
    return russianTeams.names.includes(teamName) ? 'russia' : 'world';
}

function pickRandomTeams(teamType, count) {
    const teamsData = getTeamsData(teamType);
    const available = teamsData.names.map((_, i) => i);
    const picked = [];
    // Клубный ЧМ: все клубы других континентов участвуют обязательно, остальные места — Европа
    if (teamType === 'clubwc') {
        for (let i = available.length - 1; i >= 0 && picked.length < count; i--) {
            if (NON_EUROPEAN_CLUBS.has(teamsData.names[available[i]])) picked.push(available.splice(i, 1)[0]);
        }
    }
    while (picked.length < count && available.length > 0) {
        const r = Math.floor(Math.random() * available.length);
        picked.push(available.splice(r, 1)[0]);
    }
    return picked.map(idx => ({
        name: teamsData.names[idx],
        emoji: teamsData.emojis[idx] || '⚽',
        rating: teamRatings[teamsData.names[idx]] || Math.floor(Math.random() * 20) + 70
    }));
}

function getRatingBadge(rating) {
    if (rating >= 90) return '⭐⭐⭐';
    if (rating >= 85) return '⭐⭐';
    if (rating >= 80) return '⭐';
    return '○';
}
