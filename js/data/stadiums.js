const PITCH_PATTERNS = ['stripes', 'wide', 'checks', 'diagonal', 'rings'];

// Стадион команды; у сборных и своих команд — условный, но всегда один и тот же
function stadiumOf(teamName) {
    const key = (typeof TEAM_ALIAS !== 'undefined' && TEAM_ALIAS[teamName]) || teamName;
    const s = STADIUMS[key];
    if (s) return { name: s[0], capacity: s[1], pattern: s[2] };
    const h = hashString('stadium:' + key);
    return { name: `«${teamName}» Арена`, capacity: 20000 + Math.round(h * 40000 / 1000) * 1000, pattern: PITCH_PATTERNS[Math.floor(h * PITCH_PATTERNS.length)] };
}
